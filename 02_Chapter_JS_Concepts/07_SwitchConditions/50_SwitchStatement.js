let day = "Monday";

switch (day) {
    case "Monday":
        console.log("Start of the work week");
        break;
    case "Tuesday":
        console.log("Second day of the work week");
        break;
    case "Wednesday":
        console.log("Midweek");
        break;
    case "Thursday":
        console.log("Almost the weekend");
        break;
    case "Friday":
        console.log("End of the work week");
        break;
    case "Saturday":
        console.log("Weekend");
        break;
    case "Sunday":
        console.log("Weekend");
        break;
    default:
        console.log("Invalid day");
}