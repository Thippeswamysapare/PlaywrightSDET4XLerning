let  a =10;
let b = a--;
console.log("Value of b after post-decrement: ", b);
console.log("Value of a after post-decrement: ", a);    
// This demonstrates the post-decrement operator.   
// Initial value of a: 10
// A = a-- --> A= 10 (post-decrement, a becomes 9 after this)
// Value of b after the operation: 10
// Final value of a after the entire operation: 9   